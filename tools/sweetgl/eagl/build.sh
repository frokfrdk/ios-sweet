#!/bin/bash
# Stage 7.5: build the EAGL shim for iOS arm64 (plain arm64: the port's
# userland is the non-PAC shared cache).
#   <lib dir>/libsweeteagl.a      the shim's objects, for test programs that link
#                                 Mesa themselves (test/build-eagltri.sh)
#   <out dir>/libsweeteagl.dylib  the shim with Mesa, libsweetgl and libsweetdrm
#                                 inside, for DYLD_INSERT_LIBRARIES (7.7); it
#                                 exports only sweeteagl_install
# Usage: build.sh <mesa source> <lib dir with the Mesa, sweetgl and sweetdrm libraries> <out dir>
set -euo pipefail

SRC=$(cd "$1" && pwd)
L=$(cd "$2" && pwd)
mkdir -p "$3"
OUT=$(cd "$3" && pwd)
HERE=$(cd "$(dirname "$0")" && pwd)
W=$(mktemp -d)

SDK=$(xcrun --sdk iphoneos --show-sdk-path)
CC=$(xcrun --sdk iphoneos -f clang)
CXX=$(xcrun --sdk iphoneos -f clang++)
AR=$(xcrun --sdk iphoneos -f ar)
CFLAGS=(-arch arm64 -isysroot "$SDK" -mios-version-min=16.0 -O2 -g -Wall -Wextra
  -I"$SRC/include" -I"$HERE/../sweetdrm/include" -I"$HERE/../frontend" -I"$HERE")

# The unknown-slot stubs: stub i is "mov w0, #i; b _sweeteagl_unknown_slot", 8 bytes each
{
  echo '// generated by eagl/build.sh'
  echo '	.text'
  echo '	.p2align 3'
  echo '	.globl _sweeteagl_unknown_stubs'
  echo '	.private_extern _sweeteagl_unknown_stubs'
  echo '_sweeteagl_unknown_stubs:'
  for i in $(seq 0 1035); do
    printf '\tmov\tw0, #%d\n\tb\t_sweeteagl_unknown_slot\n' "$i"
  done
} > "$W/sweeteagl_stubs.S"

"$CC" "${CFLAGS[@]}" -c "$W/sweeteagl_stubs.S" -o "$W/sweeteagl_stubs.o"
"$CC" "${CFLAGS[@]}" -std=gnu11 -c "$HERE/sweeteagl_slots.c" -o "$W/sweeteagl_slots.o"
# sweeteagl_gen.c is committed (gen_slots.py needs the local slot map)
"$CC" "${CFLAGS[@]}" -std=gnu11 -Wno-unused-parameter -c "$HERE/sweeteagl_gen.c" -o "$W/sweeteagl_gen.o"
"$CC" "${CFLAGS[@]}" -fno-objc-arc -c "$HERE/sweeteagl.m" -o "$W/sweeteagl.o"
OBJS=("$W/sweeteagl.o" "$W/sweeteagl_slots.o" "$W/sweeteagl_gen.o" "$W/sweeteagl_stubs.o")

# Mesa's archives before anything else, so every gl* the shim names is Mesa's
LIBS=()
for a in "$L"/*.a; do
  [ "$(basename "$a")" = libsweeteagl.a ] || LIBS+=("$a")
done
"$CXX" -arch arm64 -isysroot "$SDK" -mios-version-min=16.0 -dynamiclib "${OBJS[@]}" "${LIBS[@]}" \
  -install_name /usr/lib/libsweeteagl.dylib -Wl,-exported_symbol,_sweeteagl_install \
  -framework Foundation -framework IOKit -framework IOSurface -framework CoreFoundation -lobjc -lz \
  -o "$OUT/libsweeteagl.dylib"
codesign -s - -f "$OUT/libsweeteagl.dylib"

rm -f "$L/libsweeteagl.a"
"$AR" rcs "$L/libsweeteagl.a" "${OBJS[@]}"
rm -rf "$W"
