#!/usr/bin/env python3
"""
sweeteagl (Stage 7.7): generate sweeteagl_gen.c, a wrapper for every core
GLES 3.2 function that has an EAGL macro-table slot but no hand-written entry
in sweeteagl_slots.c. Each wrapper drops the context argument, logs its first
use (so a log still shows which extra calls a process makes) and calls Mesa.

The slot map is our own list of "<slot> <name> [<other name>]" lines, made
locally from OpenGLES's exported trampolines (docs/EAGL_NOTES.md); it is not
in the repository. Only the slot numbers and public GL names reach the output.

Usage: gen_slots.py <slot map> <GLES3/gl32.h> <sweeteagl_slots.c> > sweeteagl_gen.c
"""
import re
import sys

SLOTS = 1036


def prototypes(path):
    """name -> (return type, [(param decl, param name)]) for every GL_APICALL in gl32.h"""
    out = {}
    pat = re.compile(r'GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(gl\w+)\s*\((.*?)\);')
    with open(path) as f:
        for m in pat.finditer(f.read()):
            ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
            params = []
            if args and args != 'void':
                for a in args.split(','):
                    a = a.strip()
                    pn = re.search(r'(\w+)\s*(\[\d*\])?$', a)
                    params.append((a, pn.group(1)))
            out[name] = (ret, params)
    return out


def known_slots(path):
    with open(path) as f:
        return {int(s) for s in re.findall(r'\{\s*(\d+),\s*s_', f.read())}


def main():
    slotmap, header, slots_c = sys.argv[1:4]
    protos = prototypes(header)
    known = known_slots(slots_c)
    chosen = []
    with open(slotmap) as f:
        for line in f:
            fields = line.split()
            if len(fields) < 2 or not fields[0].isdigit():
                continue
            slot = int(fields[0])
            if slot >= SLOTS or slot in known:
                continue
            core = [n for n in fields[1:] if n in protos]
            if len(core) == 1:
                chosen.append((slot, core[0]))
            elif len(core) > 1:
                sys.stderr.write('slot %d: %s all core, skipped\n' % (slot, ' '.join(core)))
    chosen.sort()

    w = sys.stdout.write
    w('/* generated by eagl/gen_slots.py: core GLES 3.2 functions in EAGL macro-table slots\n'
      ' * that sweeteagl_slots.c does not handle by hand. Do not edit. */\n')
    w('#include <GLES3/gl32.h>\n\n#include "sweeteagl.h"\n\n')
    w('#define CTX     void *ctx __attribute__((unused))\n\n')
    for slot, name in chosen:
        ret, params = protos[name]
        decl = ', '.join(['CTX'] + [p for p, _ in params])
        call = ', '.join(n for _, n in params)
        body = '%s%s(%s);' % ('' if ret == 'void' else 'return ', name, call)
        w('static %s g_%s(%s)\n{\n\tsweeteagl_gen_used(ctx, %d, "%s");\n\t%s\n}\n' % (ret, name[2:], decl, slot, name, body))
    w('\nconst struct sweeteagl_gen_slot sweeteagl_gen_slots[] = {\n')
    for slot, name in chosen:
        w('\t{ %d, (void *)g_%s },\n' % (slot, name[2:]))
    w('};\n\nconst unsigned sweeteagl_gen_count = %d;\n' % len(chosen))
    sys.stderr.write('%d generated slots\n' % len(chosen))


if __name__ == '__main__':
    main()
